package com.smartspeak.english_app.user;

import org.springframework.data.jpa.repository.JpaRepository;

import java.util.Optional;

/**
 * Этот интерфейс расширяет репозиторий JPA Spring Data для сущности User.
 * Он предоставляет метод для поиска пользователя по их имени пользователя.
 */
public interface UserRepository extends JpaRepository<User, Integer> {

    /**
     * Находит пользователя по их имени пользователя.
     *
     * @param username Имя пользователя, которого нужно найти.
     * @return Опциональное значение, содержащее пользователя с указанным именем пользователя, или пустое Опциональное значение, если пользователь не найден.
     */
    Optional<User> findByUsername(String username);

    /**
     * Проверяет существование пользователя с указанным именем пользователя.
     *
     * @param username Имя пользователя, для которого нужно проверить существование.
     * @return true, если пользователь с указанным именем существует, в противном случае - false.
     */
    boolean existsByUsername(String username);

    /**
     * Проверяет существование пользователя с указанным адресом электронной почты.
     *
     * @param email Адрес электронной почты, для которого нужно проверить существование.
     * @return true, если пользователь с указанным адресом электронной почты существует, в противном случае - false.
     */
    boolean existsByEmail(String email);

    /**
     * Находит пользователя по их адресу электронной почты.
     *
     * @param email Адрес электронной почты, которого нужно найти.
     * @return Опциональное значение, содержащее пользователя с указанным адресом электронной почты, или пустое Опциональное значение, если пользователь не найден.
     */

    Optional<User> findByEmail(String email);
}