package com.smartspeak.english_app.user;

/**
 * Представляет роль пользователя в системе.
 */
public enum Role {

    PREMIUM,

    /**
     * Указывает, что пользователь не подтвержден.
     */
    UNVERIFIED,

    /**
     * Указывает, что пользователь является обычным пользователем.
     */
    USER,

    /**
     * Указывает, что пользователь является администратором.
     */
    ADMIN
}
